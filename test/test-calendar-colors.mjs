import assert from 'node:assert/strict';
import { FormulaEngine } from '../src/tinygrid.js';
import { functionHelp, documentedFunctions } from '../src/function-help.js';
const engine=new FormulaEngine({variables:new Map(),getComputedValue:(r,c)=>[['2024-02-29'],['2026-03-29']][r]?.[c]??''});
const f=text=>engine.evaluateFormula(text), iso=d=>`${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`;
assert.equal(iso(f('=EDATE("2024-01-31";1)')),'2024-02-29');
assert.equal(iso(f('=EDATE("2023-03-31";-1)')),'2023-02-28');
assert.equal(iso(f('=EOMONTH("2024-02-01";0)')),'2024-02-29');
assert.equal(f('=DATE.ISLEAP(2000)'),true);assert.equal(f('=DATE.ISLEAP(1900)'),false);
assert.equal(f('=DATE.DIFF("2026-03-28";"2026-03-30")'),2);
assert.equal(f('=DATE.DIFF("2026-10-02T12:00:00Z";"2026-10-02T14:30:00Z";"hour")'),2.5);
assert.equal(f('=DATE.ISO(DATE.ADD("2024-02-29";1;"year"))'),'2025-02-28');
assert.equal(f('=DATE.FORMAT("2026-10-02T14:05:09Z";"DD.MM.YYYY HH:mm:ss";"UTC")'),'02.10.2026 14:05:09');
assert.equal(f('=DATE.FORMAT(DATE.FROMTIMESTAMP(0);"YYYY-MM-DD HH:mm:ss";"UTC")'),'1970-01-01 00:00:00');
assert.equal(f('=ISOWEEKNUM("2021-01-01")'),53);assert.equal(f('=DATE.ISOWEEKYEAR("2021-01-01")'),2020);
assert.equal(f('=WEEKDAY("2026-10-02";2)'),5);assert.equal(f('=WEEKNUM("2021-01-01";21)'),53);
assert.equal(f('=DATEDIF("2000-02-29";"2025-02-28";"Y")'),24);
assert.equal(f('=NETWORKDAYS("2026-10-02";"2026-10-05")'),2);
assert.equal(f('=NETWORKDAYS("2026-10-05";"2026-10-02")'),-2);
engine.registerFunction('HOLIDAYS',()=>[['2026-10-05'],['2026-10-05'],['2026-10-04']]);
assert.equal(f('=NETWORKDAYS("2026-10-02";"2026-10-06";HOLIDAYS())'),2);
assert.equal(f('=DATE.ISO(WORKDAY("2026-10-02";1;HOLIDAYS()))'),'2026-10-06');
assert.equal(f('=DATE.ISO(WORKDAY("2026-10-05";-1))'),'2026-10-02');
assert.equal(f('=NETWORKDAYS.INTL("2026-10-02";"2026-10-05";"0000001")'),3);
assert.equal(f('=NETWORKDAYS.INTL("2026-10-02";"2026-10-05";"1111111")'),'#NUM!');
assert.equal(f('=TIME(25;30;0)'),'#NUM!');
assert.equal(f('=HOUR(TIME(12;34;56))'),12);assert.equal(f('=MINUTE(TIME(12;34;56))'),34);assert.equal(f('=SECOND(TIME(12;34;56))'),56);
assert.equal(f('=TIME.FORMAT(TIME.ADD("23:30";2))'),'01:30:00');
assert.equal(f('=DURATION.FORMAT(90061)'),'25:01:01');assert.equal(f('=DURATION.FORMAT(-90)'),'-00:01:30');
for(const formula of ['=TIMEVALUE("25:00")','=DATE.ISO("2026-02-30")','=DATE.ISO("2026-02-30T00:00:00Z")','=COLOR.HEX("red")'])assert.equal(f(formula),'#VALUE!',formula);
assert.deepEqual(f('=DATE.ISO(EDATE(A1:A2;1))'),[['2024-03-29'],['2026-04-29']]);
assert.equal(f('=COLOR.RGB(255;0;0)'),'#ff0000');assert.equal(f('=COLOR.HSL(120;100;50)'),'#00ff00');assert.equal(f('=COLOR.HSL(-120;100;50)'),'#0000ff');
assert.equal(f('=COLOR.HEX("#AbC")'),'#aabbcc');assert.equal(f('=COLOR.MIX("#000";"#fff";.5)'),'#808080');
assert.equal(f('=COLOR.CONTRAST("#000";"#fff")'),21);assert.equal(f('=COLOR.LUMINANCE("#fff")'),1);
assert.equal(f('=COLOR.TEXT("#fff")'),'#000000');assert.equal(f('=COLOR.TEXT("#000")'),'#ffffff');
assert.equal(f('=COLOR.COMPLEMENT("#f00")'),'#00ffff');assert.equal(f('=COLOR.INVERT("#abc")'),'#554433');
assert.equal(f('=COLOR.LIGHTEN("#000";1)'),'#ffffff');assert.equal(f('=COLOR.DARKEN("#fff";1)'),'#000000');
assert.equal(f('=COLOR.HUE("#0f0")'),120);assert.equal(f('=COLOR.SATURATION("#808080")'),0);
assert.deepEqual(f('=COLOR.PALETTE("#000";"#fff";3)'),[['#000000'],['#808080'],['#ffffff']]);
assert.equal(f('=COLOR.MIX("#000";"#fff";2)'),'#NUM!');assert.equal(f('=COLOR.PALETTE("#000";"#fff";257)'),'#NUM!');
assert.equal(f('=IFERROR(COLOR.RED("bad");42)'),42);
for(const name of Object.keys(engine.functions).filter(n=>n.startsWith('COLOR.')||n.startsWith('DATE.')||['EDATE','NETWORKDAYS','TIME'].includes(n))){assert.ok(documentedFunctions().includes(name),name);assert.notEqual(functionHelp(name,'de').description,'Benutzerdefinierte Funktion; keine Beschreibung hinterlegt.');}
assert.equal(f('=ENCODEURL("München & Berlin")'),'M%C3%BCnchen%20%26%20Berlin');
assert.equal(f('=DECODEURL(ENCODEURL("München & Berlin"))'),'München & Berlin');
assert.equal(f('=DECODEURL("%xx")'),'#VALUE!');
assert.equal(f('=WEB.GET("https://example.com")'),'#NAME? WEB.GET');
